import { test, expect } from '@playwright/test'
import { invoke, launchApp, makeTempDir } from '../helpers/app'

test('cria empresa, pasta e projeto e persiste após reiniciar', async () => {
  const dir = makeTempDir('pth-spaces-')
  let { app, page } = await launchApp(dir)
  await page.getByTestId('nav-companies').click()
  await page.getByTestId('new-company').click()
  await page.getByTestId('company-name').fill('Empresa A')
  await page.getByTestId('company-save').click()
  await expect(page.getByTestId('page-title')).toContainText('Empresa A')
  const companies = await invoke(page, 'companies.list', {})
  const empresa = companies.find((c: { name: string }) => c.name === 'Empresa A')
  const folder = await invoke(page, 'folders.create', { companyId: empresa.id, parentId: null, name: 'Clientes' })
  await page.getByTestId('space-new-project').click()
  await page.getByTestId('project-name').fill('CRM')
  await page.getByTestId('project-folder').selectOption(String(folder.id))
  await page.getByTestId('project-save').click()
  await expect(page.getByTestId('project-title')).toHaveValue('CRM')
  await expect(page.getByText('Quadro principal')).toBeVisible()
  await app.close()

  ;({ app, page } = await launchApp(dir))
  const tree = await invoke(page, 'spaces.tree', {})
  const space = tree.find((s: { company: { name: string } }) => s.company.name === 'Empresa A')
  expect(space.folders[0].name).toBe('Clientes')
  expect(space.folders[0].projects[0].name).toBe('CRM')
  await page.getByTestId('nav-companies').click()
  await page.getByTestId(`company-card-${empresa.id}`).getByText('Empresa A').click()
  await page.getByTestId('space-menu').click()
  await page.getByTestId('space-delete').click()
  await expect(page.getByTestId('confirm-ok')).toBeDisabled()
  await page.getByTestId('confirm-text').fill('Empresa A')
  await page.getByTestId('confirm-ok').click()
  await expect(page.getByTestId('page-title')).toContainText('Empresas')
  expect((await invoke(page, 'companies.list', {})).length).toBe(1)
  await app.close()
})
