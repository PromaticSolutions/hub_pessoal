-- ISO-8601 UTC with milliseconds, same format as SQLite strftime('%Y-%m-%dT%H:%M:%fZ', 'now').
CREATE FUNCTION iso_now() RETURNS text LANGUAGE sql VOLATILE AS $$
  SELECT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$;

-- Lowercase without accents (search normalisation).
CREATE FUNCTION norm_text(x text) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT translate(lower(x), 'áàâãäéèêëíìîïóòôõöúùûüçñ', 'aaaaaeeeeiiiiooooouuuucn')
$$;

