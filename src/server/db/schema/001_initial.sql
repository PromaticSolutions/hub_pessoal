-- (004) Deleted task: the block stays as a free activity with the original title.
CREATE FUNCTION tasks_bd_day_blocks() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE day_blocks SET title = OLD.title || ' (tarefa excluída)' WHERE task_id = OLD.id;
  RETURN OLD;
END $$;
CREATE TRIGGER tasks_bd_day_blocks BEFORE DELETE ON tasks FOR EACH ROW EXECUTE FUNCTION tasks_bd_day_blocks();

-- Security: RLS on every table with no policies (only the owner/service connection reads),
-- and no privileges at all for Supabase's anon/authenticated roles (when they exist).
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.tablename);
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
    REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM anon, authenticated;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM anon, authenticated;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM anon, authenticated;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON FUNCTIONS FROM anon, authenticated;
  END IF;
END $$;
