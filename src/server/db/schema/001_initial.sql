-- (002) Tasks with derived data; tasks in projects inside an archived folder (or with an archived
-- ancestor folder) count as archived. effective_archived is 0/1 like SQLite.
CREATE VIEW v_tasks AS
SELECT
  t.*,
  c.category AS status,
  c.name AS column_name,
  b.name AS board_name,
  p.id AS project_id,
  p.name AS project_name,
  p.color AS project_color,
  co.id AS company_id,
  co.name AS company_name,
  co.color AS company_color,
  co.is_personal AS is_personal,
  CASE
    WHEN t.due_at IS NULL THEN NULL
    WHEN length(t.due_at) = 10 THEN t.due_at || 'T23:59'
    ELSE t.due_at
  END AS due_end,
  (t.archived_at IS NOT NULL OR b.archived_at IS NOT NULL OR p.archived_at IS NOT NULL OR co.status = 'archived'
   OR (p.folder_id IS NOT NULL AND EXISTS (
     WITH RECURSIVE anc(id) AS (
       SELECT p.folder_id
       UNION ALL
       SELECT f.parent_id FROM folders f JOIN anc ON f.id = anc.id WHERE f.parent_id IS NOT NULL
     )
     SELECT 1 FROM anc JOIN folders f ON f.id = anc.id WHERE f.archived_at IS NOT NULL
   )))::integer AS effective_archived
FROM tasks t
JOIN columns c ON c.id = t.column_id
JOIN boards b ON b.id = t.board_id
JOIN projects p ON p.id = b.project_id
JOIN companies co ON co.id = p.company_id;

-- Text search (replaces FTS5): one row per entity, kept by triggers. norm = norm_text(title || ' ' || body).
CREATE TABLE search_index (
  entity_type text NOT NULL,
  entity_id integer NOT NULL,
  title text NOT NULL DEFAULT '',
  body text NOT NULL DEFAULT '',
  norm text NOT NULL DEFAULT '',
  PRIMARY KEY (entity_type, entity_id)
);

CREATE FUNCTION search_put(p_type text, p_id integer, p_title text, p_body text) RETURNS void LANGUAGE sql AS $$
  INSERT INTO search_index(entity_type, entity_id, title, body, norm)
  VALUES (p_type, p_id, coalesce(p_title, ''), coalesce(p_body, ''), norm_text(coalesce(p_title, '') || ' ' || coalesce(p_body, '')))
  ON CONFLICT (entity_type, entity_id) DO UPDATE SET title = excluded.title, body = excluded.body, norm = excluded.norm
$$;

-- One trigger function per entity: TG_OP DELETE removes the row, INSERT/UPDATE (re)writes it.
CREATE FUNCTION search_tasks() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN DELETE FROM search_index WHERE entity_type = 'task' AND entity_id = OLD.id; RETURN OLD; END IF;
  PERFORM search_put('task', NEW.id, NEW.title, NEW.description); RETURN NEW;
END $$;
CREATE FUNCTION search_comments() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN DELETE FROM search_index WHERE entity_type = 'comment' AND entity_id = OLD.id; RETURN OLD; END IF;
  PERFORM search_put('comment', NEW.id, '', NEW.body); RETURN NEW;
END $$;
CREATE FUNCTION search_projects() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN DELETE FROM search_index WHERE entity_type = 'project' AND entity_id = OLD.id; RETURN OLD; END IF;
  PERFORM search_put('project', NEW.id, NEW.name, NEW.description); RETURN NEW;
END $$;
CREATE FUNCTION search_companies() RETURNS trigger LANGUAGE plpgsql AS $$
